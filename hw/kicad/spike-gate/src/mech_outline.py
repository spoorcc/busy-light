def m(name):
    return MECH[name][0]


R_PCB = m("D_PCB") / 2.0
R_RING = m("D_RING") / 2.0
N_LED = m("N_LED")
USB_MOUTH_R = m("V1_USB_R0") + m("USB_L")                  # 29.85, report 4.1: "R 22.5 to 29.85"
R_OUT = 26.5                                               # script P['D_OUT'] / 2 (D_OUT 53.0)


def largest_dim_mm(mouth_r):
    """Housing largest dimension in V1 for a receptacle mouth at radius mouth_r: end wall outer face plus R_OUT.
    The script gives 57.43 mm for mouth 29.85 (report 4.1); the limit is MAX_DIM_MECH001 = 58 mm."""
    return (mouth_r - m("V1_MOUTH_IN") + m("T_WALL")) + R_OUT


def kicad_xy(mx, my, cx, cy):
    """Mechanical (x right, y up, seen from above) to KiCad board coordinates (y down)."""
    return cx + mx, cy - my


def polar(r, az_deg):
    a = math.radians(az_deg)
    return r * math.cos(a), r * math.sin(a)


def led_azimuths():
    return [m("LED_PHASE") + k * 360.0 / N_LED for k in range(N_LED)]


def led_rotation_deg(az):
    """KiCad footprint rotation for a WS2812B PLCC4 5x5 so that the footprint x axis points along the clockwise
    tangent (seen from above). Then pins 3 (GND) and 4 (DIN) face the previous LED and pins 1 (VDD) and
    2 (DOUT) face the next one, so DOUT(k) meets DIN(k+1) across the gap."""
    return (az - 90.0) % 360.0


def led_cap_shift_mm(k, az):
    """Tangential shift of the bypass cap on the underside so it clears the base posts (mech: post box
    R 20..22, 4 mm tangential, at the POST_AZ azimuths). Positive = counter-clockwise."""
    for pa in m("POST_AZ"):
        d = (az - pa + 180.0) % 360.0 - 180.0           # signed azimuth distance in degrees
        if abs(d) < 8.0:
            return (2.5 if d > 0 else -2.5)
    return 0.0


def tab_half_intersection():
    """Tab half width and the x where the tab sides meet the PCB circle."""
    hw = m("V1_TAB_W") / 2.0
    return hw, math.sqrt(R_PCB ** 2 - hw ** 2)


def outline_segments(tab_r=None):
    """Edge.Cuts outline as a list of ('arc', start, mid, end) / ('line', start, end) in mechanical mm,
    counter-clockwise from the upper tab junction. Circle R_PCB, tab of width V1_TAB_W to V1_TAB_R, notch."""
    hw, xj = tab_half_intersection()
    b = math.degrees(math.asin(hw / R_PCB))                  # tab junction azimuth
    nr, naz = m("NOTCH_R"), m("NOTCH_AZ")
    ncx, ncy = polar(R_PCB, naz)
    # notch circle (centre on the PCB edge at NOTCH_AZ, radius NOTCH_R) meets the PCB circle at +-d around naz
    d = math.degrees(math.acos(1.0 - nr ** 2 / (2.0 * R_PCB ** 2)))
    a1, a2 = naz - d, naz + d
    seg = []
    seg.append(("arc", polar(R_PCB, b), polar(R_PCB, (b + a1) / 2), polar(R_PCB, a1)))
    inward = polar(R_PCB - nr, naz)
    seg.append(("arc", polar(R_PCB, a1), inward, polar(R_PCB, a2)))
    seg.append(("arc", polar(R_PCB, a2), polar(R_PCB, (a2 + 360.0 - b) / 2), polar(R_PCB, 360.0 - b)))
    tr = m("V1_TAB_R") if tab_r is None else tab_r
    seg.append(("line", polar(R_PCB, 360.0 - b), (tr, -hw)))
    seg.append(("line", (tr, -hw), (tr, hw)))
    seg.append(("line", (tr, hw), polar(R_PCB, b)))
    return seg


def inside_pcb(x, y, margin=0.0, tab_r=None):
    """Point inside the PCB (circle or tab), at least `margin` from the edge (notch ignored, it is 1.5 mm)."""
    hw = m("V1_TAB_W") / 2.0
    if math.hypot(x, y) <= R_PCB - margin:
        return True
    tr = m("V1_TAB_R") if tab_r is None else tab_r
    return (R_PCB - m("V1_TAB_ROOT") <= x <= tr - margin) and abs(y) <= hw - margin


def hook_keepouts():
    """Top-side footprint keep-out under the three hook lugs: rectangles in polar frame (r0, r1, half
    tangential width) at the POST_AZ azimuths. Hook lug: R_PCB - HOOK_OVERLAP .. R_PCB + peg, 4 mm wide."""
    r0 = R_PCB - m("HOOK_OVERLAP")
    return [(az, r0, R_PCB + 0.5, m("POST_TANG") / 2.0) for az in m("POST_AZ")]


def post_keepouts():
    """Bottom-side keep-out (the base posts under the PCB edge): (az, r0, r1, half tangential width)."""
    rp, w = m("R_POST"), m("POST_RAD") / 2.0
    return [(az, rp - w, rp + w, m("POST_TANG") / 2.0) for az in m("POST_AZ")]


def module_rect():
    """Module body on the top side: (x0, y0, x1, y1) mm mechanical, long axis along X, antenna end at -X."""
    off, L, W = m("MOD_OFF"), m("MOD_L"), m("MOD_W")
    return (-L / 2 + off, -W / 2, L / 2 + off, W / 2)


def antenna_strip():
    """Antenna strip of the module (x0, y0, x1, y1): the part of the board under it must have no copper."""
    x0, y0, x1, y1 = module_rect()
    return (x0, y0, x0 + m("MOD_ANT_L"), y1)


def vendor_keepout_rect():
    """Vendor recommendation: ANT_KEEPOUT mm beyond the module end in the antenna direction (not met, see report)."""
    x0, y0, x1, y1 = module_rect()
    return (x0 - m("ANT_KEEPOUT"), y0, x0, y1)


def region_rect_ok(side, x0, y0, x1, y1, r_move=16.6, tab_r=None):
    """Region where movable parts may sit, mechanical coordinates. Top (F): inside r_move and outside the module.
    Bottom (B): inside r_move, or on the tab behind the LED ring. Never in the antenna strip."""
    pts = [(x0, y0), (x0, y1), (x1, y0), (x1, y1)]
    ax0, ay0, ax1, ay1 = antenna_strip()
    if x1 > ax0 - 0.3 and x0 < ax1 + 0.3 and y1 > ay0 - 0.3 and y0 < ay1 + 0.3:
        return False
    if side == "F":
        mx0, my0, mx1, my1 = module_rect()
        if x1 > mx0 - 0.3 and x0 < mx1 + 0.3 and y1 > my0 - 0.3 and y0 < my1 + 0.3:
            return False
        return all(math.hypot(px, py) <= r_move for px, py in pts)
    hw = m("V1_TAB_W") / 2.0 - 0.7
    tr = m("V1_TAB_R") if tab_r is None else tab_r
    on_tab = x0 >= 22.9 and x1 <= tr - 0.7 and y0 >= -hw and y1 <= hw
    return on_tab or all(math.hypot(px, py) <= r_move for px, py in pts)
