"""Spike: mechanical envelope of the PCB, taken from the FreeCAD spike model (CAD as code).

SPIKE ONLY. The source is a concept spike, not an Approved design: MECH requirements and plan 05 are Draft,
ADR-0011 (housing concept) is the basis, no variant of the USB-C position is chosen (HW-005, ADR-0003 open).
Nothing here is released. Every number below has a source line; where the model uses a placeholder it says so.

Source of every number: branch `spike/mech-concept`, commit deb9a5c,
  file mech/freecad/busy_light_housing.py (parameter block P, variant V1), and
  report docs/verification/reports/mech-spike-model.md (sections 4.1, 5, 6) on the same branch.
The FCStd files in the worktree .claude/worktrees/agent-ac020049007f58faf/mech/ were generated by that script
(V1, V2-posts and V2-pocket results.json agree with the script); the script is the readable source.

Variant choice: V1 (PCB tab at azimuth 0 carries the USB-C receptacle outside the LED ring). Reason: it is the
only variant of the three in the report that passes all 41 checks without breaking SYS-022 (one-side assembly,
report 4.1 "V2 conflicts with the one-side assembly rule SYS-022"). V0 fails (receptacle overlaps the LED ring).
V2-pocket and V2-posts are alternatives: the receptacle is on the PCB underside at azimuth 0, mouth at the
PCB edge, no tab; they need a different outline (plain disc D46) and put J1 on the bottom side.

Coordinates here are mechanical: mm, origin at the housing axis, azimuth 0 = +X, counter-clockwise seen from
above (LED side up). `kicad_xy` converts to KiCad board coordinates (y down), seen from above.
This module has no KiCad dependency, so the tests run with any Python.
"""
