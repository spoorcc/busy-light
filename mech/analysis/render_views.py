"""Draw README views of the housing model from the mesh JSON (matplotlib, Agg backend).

Usage: python3 -I render_views.py <mesh.json> <out dir>
Output: housing-model-exploded.png (isometric, lid lifted, accessory below) and
housing-model-back.png (view of the back: bayonet groove with lips, label centre open).
Tool output only; the images show the generated model, not a photo or a hand drawing.
"""

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib.collections import PolyCollection  # noqa: E402

COLORS = {"base": (0.35, 0.37, 0.40), "lid": (0.55, 0.75, 0.95), "accessory": (0.85, 0.55, 0.25)}
LIGHT = np.array([0.4, -0.5, 0.75])  # fixed light direction
LIGHT = LIGHT / np.linalg.norm(LIGHT)


def subdivide(tri, max_edge):
    """Split triangles until every edge is shorter than max_edge (keeps the painter order right)."""
    while True:
        e = np.max(
            [np.linalg.norm(tri[:, i] - tri[:, (i + 1) % 3], axis=1) for i in range(3)], axis=0
        )
        big = e > max_edge
        if not big.any():
            return tri
        keep, split = tri[~big], tri[big]
        a, b, c = split[:, 0], split[:, 1], split[:, 2]
        ab, bc, ca = (a + b) / 2, (b + c) / 2, (c + a) / 2
        new = np.concatenate(
            [np.stack(x, axis=1) for x in ((a, ab, ca), (ab, b, bc), (ca, bc, c), (ab, bc, ca))]
        )
        tri = np.concatenate([keep, new])


def camera(elev, azim):
    """Orthographic camera: returns (right, up, toward-viewer) unit vectors."""
    el, az = np.radians(elev), np.radians(azim)
    toward = np.array([np.cos(el) * np.cos(az), np.cos(el) * np.sin(az), np.sin(el)])
    right = np.cross([0, 0, 1], toward)
    right /= np.linalg.norm(right)
    up = np.cross(toward, right)
    return right, up, toward


def draw(meshes, placed, path, view):
    """view = (elevation, azimuth, title, light direction)."""
    elev, azim, title, light = view
    right, up, toward = camera(elev, azim)
    polys, depth, cols = [], [], []
    for name, (dx, dz) in placed.items():
        v = np.array(meshes[name]["v"], dtype=float)
        v[:, 0] += dx
        v[:, 2] += dz
        tri = subdivide(v[np.array(meshes[name]["t"])], 3.0)
        n = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
        n /= np.linalg.norm(n, axis=1, keepdims=True) + 1e-12
        n *= np.sign(np.sum(n * toward, axis=1, keepdims=True) + 1e-12)  # two-sided light
        shade = 0.35 + 0.65 * np.clip(n @ light, 0, 1)
        centre = tri.mean(axis=1)
        polys.append(np.stack([tri @ right, tri @ up], axis=-1))
        depth.append(centre @ toward)
        cols.append(np.clip(shade[:, None] * np.array(COLORS[name])[None, :] * 1.2, 0, 1))
    polys, depth, cols = np.concatenate(polys), np.concatenate(depth), np.concatenate(cols)
    order = np.argsort(depth)
    fig, ax = plt.subplots(figsize=(8, 6), dpi=150)
    ax.add_collection(
        PolyCollection(polys[order], facecolors=cols[order], edgecolors=cols[order], lw=0.2)
    )
    ax.autoscale()
    ax.set_aspect("equal")
    ax.set_axis_off()
    ax.set_title(title, fontsize=9)
    fig.savefig(path, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def main(argv):
    mesh = json.loads(Path(argv[1]).read_text())
    out = Path(argv[2])
    out.mkdir(parents=True, exist_ok=True)
    title = "Housing model, exploded: lid, base, accessory ring (generated by FreeCAD script)"
    draw(
        mesh,
        {"base": (0, 0), "lid": (0, 12), "accessory": (0, -8)},
        out / "housing-model-exploded.png",
        (25, -60, title, LIGHT),
    )
    title = (
        "Back of the base: bayonet groove with entry sectors, lips and stops (label centre open)"
    )
    draw(
        mesh,
        {"base": (0, 0)},
        out / "housing-model-back.png",
        (-60, -90, title, LIGHT * np.array([1, 1, -1])),
    )
    print("render: wrote", out)


if __name__ == "__main__":
    main(sys.argv)
